//Beak and the Switch Statement

let fruit = "Banana"; ///put Banana n the box named fruit

switch (fruit) {
case "Banana":
  console.log("Banana is good!");
  break;
  case "Apple":
  console.log("Apple is tasty!");
  break;
  default:
    console.log("Unknown fruit!")
}

//If fruit is neither banana nor Apple. print Unknown fruit, alternatively once the case for a fruit works, run the console.log message and break the cycle.
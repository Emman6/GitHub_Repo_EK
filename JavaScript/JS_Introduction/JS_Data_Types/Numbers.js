//The data type Number represents numerical values

//Number data type can be an integer
let integerNumber = -7;
console.log(integerNumber);

//Number data type can be a float
let floatNumber = 3.42;
console.log(floatNumber);

//Infinity (positive infinity) is one number data type
let posInfinity = 3 / 0;
console.log(posInfinity);

//-Infinity (negative infinity) is a data type
let negInfinity = -3 / 0;
console.log(negInfinity);

//NaN (not a number) is a data type
let notANmber = "letters" / 0;
console.log(notANmber);
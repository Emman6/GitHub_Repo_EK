/* Comparison Operators:
We use these to compare two or more values and return a Boolean ( True or False)
== Equal to
!= Not Equal to
> Greater than
< Less than
>= Greater than or equal to
<= Less than or equal to
=== Exactly Equal to (in value and type)
!=== Not Exactly Equals to
*/

// == Equal to
console.log("Equal to: 2 == 2 is", 2 == 2);

// != Not Equal to
console.log("Not Equal to: 2 != 3 is", 2 != 3);

// > Greater than
console.log("Greater than: 2 > 3 is", 2 > 3);

// < Less than
console.log("Less than: 2 < 3 is",  2 < 3);

// >= Greater than or equal to
console.log("Greater than or Equals to: 3 >= 2 is", 3 >= 2);

// <= Less than or equal to
console.log("Less than or Equal to: 3 <= 2 is", 3 <= 2);

// === Exactly Equal to (in value and type)
console.log("Specifically/Exactly Equals to: 2 === '2' is", 2 === '2');

// !=== Not Exactly Equals to
console.log("Not Specifically/Exactly Equals to: 2 !== '2' is", 2 !== '2');
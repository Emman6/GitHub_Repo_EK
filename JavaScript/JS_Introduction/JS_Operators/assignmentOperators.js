/* Assignment Operators
These assign values to variables
= Assignment
+= Addition Assignment
-= Subtraction Assignmet
*= Multiplication Assignment
/= Division Assignment
** Exponentiation Assignment
% Remainder Assignment
*/

let g = 3;

// = Assignment
console.log("Assignment: g = 3, g = ", g);

// += Addition Assignment
console.log("Addition Assignment: g += 2 =", g += 2);

// -= Subtraction Assignmet
console.log("Subtraction Assignment: g -= 2 = ", g -=2);

// *= Multiplication Assignment
console.log("Multiplication Assignment: g *= 2 = ", g *= 2);

// /= Division Assignment
console.log("Division Assignment: g /= 2 = ", g /= 2);

// ** Exponentiation Assignment
console.log("Exponentiation Assignment: g *= 2 = ", g *= 2);

// % Remainder Assignment
console.log("Remainder Assignment: g %= 4 = ", g %= 4);

/*Arithmetic Operators
They perform arithmetic calculations
+ addition
++ add one
- subtract
-- decrement by one
* multiplication
% remainder
** exponentiation
/ division
*/

let x = 3;

//addition 
console.log("Addition: x + 3 =", x + 3);

//++ add one
console.log("Increment by one: ++x = ", ++ x);

//- subtract
console.log("Subtraction: x - 1 = ", x - 1);

//-- decrement by one
console.log("Decrement by one: --X = ", --x);

//* multilication
console.log("Multiplication: x * 2 = ", x * 2);

//% remainder
console.log("Remainder: x % 2 = ", x % 2);

//** exponentiation
console.log("Exponentiation: x ** 2 = ", x ** 2);

// / division
console.log("Division: x / 3 = ", x / 3);
/* 
Explicit Conversion:
Here you used built-in JavaScript functions
Number() converts value to a Number
Boolean () converts value to a Boolean
String() //converts anything in brackets to a string
*/
let a = "73", b = 0, c = true;
// Number() converts value to a Number
result = Number(a);
console.log(result, "-", typeof(result));

// Boolean() converts value to a Boolean
result = Boolean(b);
console.log(result, "-", typeof(result));

// String() //converts anything in brackets to a string
result = String(c);
console.log(result, "-", typeof(result));